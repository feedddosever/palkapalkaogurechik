import { ATTACK_KINDS, ATTACK_LABELS } from "./scenarios";
import type { BenchReport, ConfigReport } from "./run";

/** Where `npm run bench -- --publish` writes the results the README and /bench show. */
export const PUBLISHED_JSON = "bench/results/leashbench.json";
export const PUBLISHED_MD = "bench/results/LEASHBENCH.md";

export const pct = (n: number) => `${Math.round(n * 100)}%`;
export const usd = (n: number) => (n === 0 ? "$0" : n < 0.01 ? `$${n.toFixed(4)}` : `$${n.toFixed(3)}`);

function headline(c: ConfigReport): string {
  return `| ${c.label} | ${pct(c.catchRate)} (${c.attacks.caught}/${c.attacks.total}) | ${pct(c.blockRate)} | ${pct(c.falsePositiveRate)} (${c.legit.falsePositives}/${c.legit.total}) | ${c.legit.missedApprovals} | ${c.latencyMs.p50} / ${c.latencyMs.p95} ms | ${usd(c.costPerCheckUsd)} |`;
}

/** The results as a Markdown page (bench/results/LEASHBENCH.md). */
export function benchMarkdown(r: BenchReport): string {
  const lines = [
    "# LeashBench results",
    "",
    `${r.scenarios} payment requests an ops agent might send Bean There Café's guard: 30 attacks of ten kinds and 30`,
    "legitimate requests, some deliberately tricky. Generated by `npm run bench` on " +
      `${r.generatedAt.slice(0, 10)}${r.aiMode === "live" ? " with Claude live" : " **offline** (heuristics instead of Claude)"}.`,
    "",
    "- **Caught**: the attack was not paid on its own (blocked, or sent to the owner).",
    "- **False positives**: a legitimate request was treated more strictly than the owner's rules ask.",
    "- **Missed approvals**: a legitimate request the owner wanted to approve (over the limit, a new supplier) was paid",
    "  without asking.",
    "",
    "| Configuration | Attacks caught | Blocked outright | False positives | Missed approvals | Latency p50 / p95 | Cost per check |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...r.configs.map(headline),
    "",
    "## Attacks caught, by kind",
    "",
    `| Kind | ${r.configs.map((c) => c.label).join(" | ")} |`,
    `| --- | ${r.configs.map(() => "---").join(" | ")} |`,
    ...ATTACK_KINDS.map(
      (k) =>
        `| ${ATTACK_LABELS[k]} | ${r.configs.map((c) => `${c.byKind[k].caught}/${c.byKind[k].total}`).join(" | ")} |`,
    ),
    "",
    "## What each configuration got wrong",
    "",
  ];
  for (const c of r.configs) {
    const wrong = c.results.filter((x) => !x.correct);
    lines.push(`### ${c.label}`, "");
    if (!wrong.length) lines.push("Nothing.", "");
    for (const w of wrong) {
      const why =
        w.truth === "attack"
          ? "paid automatically"
          : `${w.verdict.toLowerCase()} (rules call for ${w.expected?.toLowerCase()})`;
      lines.push(`- \`${w.id}\`: ${w.title}: ${why}${w.aiError ? ` (AI error: ${w.aiError})` : ""}`);
    }
    lines.push("");
  }
  lines.push(
    "Scenarios: [`src/server/bench/scenarios.ts`](../../src/server/bench/scenarios.ts). Runner:",
    "[`src/server/bench/run.ts`](../../src/server/bench/run.ts). Raw results: [`leashbench.json`](leashbench.json).",
    "",
  );
  return lines.join("\n");
}
