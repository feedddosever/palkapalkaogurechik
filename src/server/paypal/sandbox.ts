import {
  ApiError,
  CheckoutPaymentIntent,
  Client,
  Environment,
  LogLevel,
  OrdersController,
  PaymentsController,
  PaypalExperienceUserAction,
  PaypalPaymentTokenCustomerType,
  PaypalPaymentTokenUsageType,
  PaypalWalletContextShippingPreference,
  StoreInVaultInstruction,
  TransactionSearchController,
  type ApiResponse,
  type Order,
  type PaymentAuthorization,
} from "@paypal/paypal-server-sdk";
import { normalizeAmount } from "@/lib/money";
import {
  AUTHORIZATION_VALID_DAYS,
  HONOR_PERIOD_DAYS,
  PayPalError,
  type AuthorizationInfo,
  type AuthorizationStatus,
  type CaptureInfo,
  type CaptureInput,
  type CreateHoldOrderInput,
  type HoldOrder,
  type OrderStatus,
  type PayoutInfo,
  type PayoutInput,
  type PayPalGateway,
  type RefundInfo,
  type TransactionSummary,
} from "./types";

const SANDBOX_BASE = "https://api-m.sandbox.paypal.com";
const DAY = 24 * 60 * 60 * 1000;
const PREFER = "return=representation";

/**
 * The real PayPal sandbox.
 * Orders, Payments and Transaction Search use the official PayPal Server SDK (generated by
 * APIMatic). Payouts and webhook verification are not in the SDK, so they go through a small
 * typed REST client that shares the same error model.
 */
export class SandboxPayPal implements PayPalGateway {
  readonly mode = "sandbox" as const;
  private readonly orders: OrdersController;
  private readonly payments: PaymentsController;
  private readonly reporting: TransactionSearchController;
  private token?: { value: string; expiresAt: number };

  constructor(private readonly creds: { clientId: string; clientSecret: string }) {
    const client = new Client({
      clientCredentialsAuthCredentials: {
        oAuthClientId: creds.clientId,
        oAuthClientSecret: creds.clientSecret,
      },
      environment: Environment.Sandbox,
      timeout: 20_000,
      logging: {
        logLevel: LogLevel.Warn,
        logRequest: { logBody: false },
        logResponse: { logHeaders: false },
      },
    });
    this.orders = new OrdersController(client);
    this.payments = new PaymentsController(client);
    this.reporting = new TransactionSearchController(client);
  }

  // ─── orders ───────────────────────────────────────────────────────────────

  async createHoldOrder(input: CreateHoldOrderInput): Promise<HoldOrder> {
    const res = await sdk(() =>
      this.orders.createOrder({
        paypalRequestId: input.requestId,
        prefer: PREFER,
        body: {
          intent: CheckoutPaymentIntent.Authorize,
          purchaseUnits: [
            {
              referenceId: input.customId,
              customId: input.customId,
              invoiceId: input.invoiceId,
              description: input.description,
              amount: { currencyCode: input.currency, value: normalizeAmount(input.amount) },
            },
          ],
          paymentSource: {
            paypal: {
              experienceContext: {
                brandName: input.brandName ?? "Leash",
                returnUrl: input.returnUrl,
                cancelUrl: input.cancelUrl,
                shippingPreference: PaypalWalletContextShippingPreference.NoShipping,
                userAction: PaypalExperienceUserAction.Continue,
              },
              attributes: input.vault
                ? {
                    vault: {
                      storeInVault: StoreInVaultInstruction.OnSuccess,
                      usageType: PaypalPaymentTokenUsageType.Merchant,
                      customerType: PaypalPaymentTokenCustomerType.Consumer,
                      permitMultiplePaymentTokens: true,
                    },
                  }
                : undefined,
            },
          },
        },
      }),
    );
    return toHoldOrder(res.result, debugId(res));
  }

  async getOrder(orderId: string): Promise<HoldOrder> {
    const res = await sdk(() => this.orders.getOrder({ id: orderId }));
    return toHoldOrder(res.result, debugId(res));
  }

  async authorizeOrder(orderId: string, { requestId }: { requestId: string }): Promise<AuthorizationInfo> {
    const res = await sdk(() =>
      this.orders.authorizeOrder({ id: orderId, paypalRequestId: requestId, prefer: PREFER }),
    );
    return authorizationFromOrder(res.result, debugId(res));
  }

  async authorizeWithVault(input: {
    vaultId: string;
    amount: string;
    currency: string;
    description: string;
    customId: string;
    requestId: string;
  }): Promise<AuthorizationInfo> {
    const res = await sdk(() =>
      this.orders.createOrder({
        paypalRequestId: input.requestId,
        prefer: PREFER,
        body: {
          intent: CheckoutPaymentIntent.Authorize,
          purchaseUnits: [
            {
              referenceId: input.customId,
              customId: input.customId,
              description: input.description,
              amount: { currencyCode: input.currency, value: normalizeAmount(input.amount) },
            },
          ],
          paymentSource: { paypal: { vaultId: input.vaultId } },
        },
      }),
    );
    // With a vaulted wallet PayPal usually completes the order straight away. If it doesn't,
    // authorize explicitly (same idempotency key namespace, different operation).
    if (res.result.status === "COMPLETED") return authorizationFromOrder(res.result, debugId(res));
    return this.authorizeOrder(res.result.id!, { requestId: `${input.requestId}-auth` });
  }

  async getAuthorization(authorizationId: string): Promise<AuthorizationInfo> {
    const res = await sdk(() => this.payments.getAuthorizedPayment({ authorizationId }));
    return toAuthInfo(res.result, debugId(res));
  }

  // ─── payments ─────────────────────────────────────────────────────────────

  async capture(authorizationId: string, input: CaptureInput): Promise<CaptureInfo> {
    const res = await sdk(() =>
      this.payments.captureAuthorizedPayment({
        authorizationId,
        paypalRequestId: input.requestId,
        prefer: PREFER,
        body: {
          amount: { currencyCode: input.currency, value: normalizeAmount(input.amount) },
          finalCapture: input.finalCapture,
          invoiceId: input.invoiceId,
          noteToPayer: input.noteToPayer,
        },
      }),
    );
    const c = res.result;
    return {
      captureId: c.id!,
      authorizationId,
      status: (c.status ?? "PENDING") as CaptureInfo["status"],
      amount: { value: c.amount?.value ?? input.amount, currency: c.amount?.currencyCode ?? input.currency },
      finalCapture: c.finalCapture ?? input.finalCapture,
      invoiceId: c.invoiceId,
      debugId: debugId(res),
    };
  }

  async voidAuthorization(
    authorizationId: string,
    { requestId }: { requestId: string },
  ): Promise<AuthorizationInfo> {
    const res = await sdk(() =>
      this.payments.voidPayment({ authorizationId, paypalRequestId: requestId, prefer: PREFER }),
    );
    // PayPal may answer 204 (no body); fetch the authorization to report its final state.
    if (!res.result?.id) return this.getAuthorization(authorizationId);
    return toAuthInfo(res.result, debugId(res));
  }

  async reauthorize(
    authorizationId: string,
    input: { amount: string; currency: string; requestId: string },
  ): Promise<AuthorizationInfo> {
    const res = await sdk(() =>
      this.payments.reauthorizePayment({
        authorizationId,
        paypalRequestId: input.requestId,
        prefer: PREFER,
        body: { amount: { currencyCode: input.currency, value: normalizeAmount(input.amount) } },
      }),
    );
    return toAuthInfo(res.result, debugId(res));
  }

  async refundCapture(
    captureId: string,
    input: { amount: string; currency: string; requestId: string; note?: string },
  ): Promise<RefundInfo> {
    const res = await sdk(() =>
      this.payments.refundCapturedPayment({
        captureId,
        paypalRequestId: input.requestId,
        prefer: PREFER,
        body: {
          amount: { currencyCode: input.currency, value: normalizeAmount(input.amount) },
          noteToPayer: input.note,
        },
      }),
    );
    const r = res.result;
    return {
      refundId: r.id!,
      status: r.status ?? "PENDING",
      amount: { value: r.amount?.value ?? input.amount, currency: r.amount?.currencyCode ?? input.currency },
      debugId: debugId(res),
    };
  }

  // ─── payouts (REST) ───────────────────────────────────────────────────────

  async createPayout(input: PayoutInput): Promise<PayoutInfo> {
    const { body, debugId: dbg } = await this.rest<PayoutResponse>("POST", "/v1/payments/payouts", {
      // PayPal-Request-Id makes a retried batch replay instead of paying twice.
      requestId: input.senderBatchId,
      body: {
        sender_batch_header: { sender_batch_id: input.senderBatchId, email_subject: input.emailSubject },
        items: input.items.map((i) => ({
          recipient_type: "EMAIL",
          receiver: i.receiver,
          note: i.note,
          sender_item_id: i.senderItemId,
          amount: { value: normalizeAmount(i.amount), currency: i.currency },
        })),
      },
    });
    return toPayout(body, input, dbg);
  }

  async getPayout(batchId: string): Promise<PayoutInfo> {
    const { body, debugId: dbg } = await this.rest<PayoutResponse>(
      "GET",
      `/v1/payments/payouts/${encodeURIComponent(batchId)}`,
    );
    return toPayout(body, undefined, dbg);
  }

  // ─── webhooks & reporting ─────────────────────────────────────────────────

  async verifyWebhook({
    headers,
    event,
    webhookId,
  }: {
    headers: Record<string, string | undefined>;
    event: unknown;
    webhookId: string;
  }): Promise<boolean> {
    const h = (name: string) => headers[name] ?? headers[name.toLowerCase()];
    const { body } = await this.rest<{ verification_status: string }>(
      "POST",
      "/v1/notifications/verify-webhook-signature",
      {
        body: {
          auth_algo: h("paypal-auth-algo"),
          cert_url: h("paypal-cert-url"),
          transmission_id: h("paypal-transmission-id"),
          transmission_sig: h("paypal-transmission-sig"),
          transmission_time: h("paypal-transmission-time"),
          webhook_id: webhookId,
          webhook_event: event,
        },
      },
    );
    return body.verification_status === "SUCCESS";
  }

  async searchTransactions({
    startDate,
    endDate,
  }: {
    startDate: Date;
    endDate: Date;
  }): Promise<TransactionSummary[]> {
    const res = await sdk(() =>
      this.reporting.searchTransactions({
        startDate: startDate.toISOString(),
        endDate: endDate.toISOString(),
        fields: "transaction_info",
        pageSize: 500,
      }),
    );
    return (res.result.transactionDetails ?? []).flatMap((d) => {
      const t = d.transactionInfo;
      if (!t?.transactionId) return [];
      return [
        {
          id: t.transactionId,
          type: eventCodeToType(t.transactionEventCode),
          status: t.transactionStatus ?? "",
          amount: {
            value: t.transactionAmount?.value ?? "0.00",
            currency: t.transactionAmount?.currencyCode ?? "USD",
          },
          at: t.transactionInitiationDate ?? "",
          invoiceId: t.invoiceId,
          refId: t.paypalReferenceId,
        },
      ];
    });
  }

  // ─── REST plumbing ────────────────────────────────────────────────────────

  private async accessToken(): Promise<string> {
    if (this.token && this.token.expiresAt > Date.now() + 60_000) return this.token.value;
    const res = await fetch(`${SANDBOX_BASE}/v1/oauth2/token`, {
      method: "POST",
      headers: {
        Authorization: `Basic ${Buffer.from(`${this.creds.clientId}:${this.creds.clientSecret}`).toString("base64")}`,
        "Content-Type": "application/x-www-form-urlencoded",
      },
      body: "grant_type=client_credentials",
    });
    const json = (await res.json().catch(() => ({}))) as {
      access_token?: string;
      expires_in?: number;
      error_description?: string;
    };
    if (!res.ok || !json.access_token) {
      throw new PayPalError(
        "AUTHENTICATION_FAILURE",
        json.error_description ?? "PayPal OAuth failed",
        res.status,
      );
    }
    this.token = { value: json.access_token, expiresAt: Date.now() + (json.expires_in ?? 300) * 1000 };
    return this.token.value;
  }

  private async rest<T>(
    method: "GET" | "POST",
    path: string,
    { body, requestId }: { body?: unknown; requestId?: string } = {},
  ): Promise<{ body: T; debugId?: string }> {
    const res = await fetch(`${SANDBOX_BASE}${path}`, {
      method,
      headers: {
        Authorization: `Bearer ${await this.accessToken()}`,
        "Content-Type": "application/json",
        ...(requestId ? { "PayPal-Request-Id": requestId } : {}),
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const dbg = res.headers.get("paypal-debug-id") ?? undefined;
    const text = await res.text();
    const json = text ? (JSON.parse(text) as unknown) : {};
    if (!res.ok) throw toPayPalError(json, res.status, dbg);
    return { body: json as T, debugId: dbg };
  }
}

// ─── mapping helpers ────────────────────────────────────────────────────────

type PayoutResponse = {
  batch_header?: {
    payout_batch_id?: string;
    batch_status?: string;
    sender_batch_header?: { sender_batch_id?: string };
  };
  items?: {
    payout_item_id?: string;
    transaction_status?: string;
    payout_item?: {
      receiver?: string;
      sender_item_id?: string;
      amount?: { value?: string; currency?: string };
    };
  }[];
};

/** Calls the SDK and converts its errors into PayPalError. */
async function sdk<T>(call: () => Promise<ApiResponse<T>>): Promise<ApiResponse<T>> {
  try {
    return await call();
  } catch (err) {
    if (err instanceof ApiError) {
      let parsed: unknown = err.result;
      if (!parsed && typeof err.body === "string") {
        try {
          parsed = JSON.parse(err.body);
        } catch {
          parsed = undefined;
        }
      }
      throw toPayPalError(parsed, err.statusCode, err.headers?.["paypal-debug-id"]);
    }
    if (err instanceof PayPalError) throw err;
    throw new PayPalError("NETWORK_ERROR", err instanceof Error ? err.message : "PayPal request failed");
  }
}

export function toPayPalError(body: unknown, status: number, dbg?: string): PayPalError {
  const b = (body ?? {}) as {
    name?: string;
    message?: string;
    debug_id?: string;
    details?: { issue?: string; description?: string }[];
    error?: string;
    error_description?: string;
  };
  const issue = b.details?.[0]?.issue;
  const code = issue ?? b.name ?? b.error ?? `HTTP_${status}`;
  const message =
    b.details?.[0]?.description ?? b.message ?? b.error_description ?? `PayPal returned ${status}`;
  return new PayPalError(code, message, status, b.debug_id ?? dbg, b.details);
}

function debugId(res: ApiResponse<unknown>): string | undefined {
  return res.headers?.["paypal-debug-id"];
}

function toHoldOrder(o: Order, dbg?: string): HoldOrder {
  const approve = o.links?.find((l) => l.rel === "payer-action" || l.rel === "approve");
  return {
    orderId: o.id!,
    status: (o.status ?? "CREATED") as OrderStatus,
    approveUrl: approve?.href,
    payerEmail: o.paymentSource?.paypal?.emailAddress ?? o.payer?.emailAddress,
    debugId: dbg,
  };
}

function authorizationFromOrder(o: Order, dbg?: string): AuthorizationInfo {
  const auth = o.purchaseUnits?.[0]?.payments?.authorizations?.[0];
  if (!auth?.id)
    throw new PayPalError("AUTHORIZATION_MISSING", `Order ${o.id} returned no authorization`, 502, dbg);
  return {
    ...toAuthInfo(auth, dbg),
    orderId: o.id,
    vaultId: o.paymentSource?.paypal?.attributes?.vault?.id,
    payerEmail: o.paymentSource?.paypal?.emailAddress ?? o.payer?.emailAddress,
    payerId: o.paymentSource?.paypal?.accountId ?? o.payer?.payerId,
  };
}

function toAuthInfo(a: PaymentAuthorization, dbg?: string): AuthorizationInfo {
  const created = a.createTime ? new Date(a.createTime) : new Date();
  return {
    authorizationId: a.id!,
    status: (a.status ?? "CREATED") as AuthorizationStatus,
    amount: { value: a.amount?.value ?? "0.00", currency: a.amount?.currencyCode ?? "USD" },
    honorUntil: new Date(created.getTime() + HONOR_PERIOD_DAYS * DAY).toISOString(),
    expiresAt: a.expirationTime ?? new Date(created.getTime() + AUTHORIZATION_VALID_DAYS * DAY).toISOString(),
    debugId: dbg,
  };
}

function toPayout(p: PayoutResponse, input: PayoutInput | undefined, dbg?: string): PayoutInfo {
  return {
    batchId: p.batch_header?.payout_batch_id ?? "",
    senderBatchId: p.batch_header?.sender_batch_header?.sender_batch_id ?? input?.senderBatchId ?? "",
    status: (p.batch_header?.batch_status ?? "PENDING") as PayoutInfo["status"],
    items:
      p.items?.map((i) => ({
        itemId: i.payout_item_id,
        senderItemId: i.payout_item?.sender_item_id ?? "",
        receiver: i.payout_item?.receiver ?? "",
        amount: {
          value: i.payout_item?.amount?.value ?? "0.00",
          currency: i.payout_item?.amount?.currency ?? "USD",
        },
        status: i.transaction_status,
      })) ??
      input?.items.map((i) => ({
        senderItemId: i.senderItemId,
        receiver: i.receiver,
        amount: { value: normalizeAmount(i.amount), currency: i.currency },
      })) ??
      [],
    debugId: dbg,
  };
}

/** PayPal transaction event codes → a short type (T00xx payments, T11xx refunds, T0400 payouts…). */
export function eventCodeToType(code?: string): string {
  if (!code) return "other";
  if (code === "T1105" || code === "T1106") return "authorization";
  if (code.startsWith("T11")) return "refund";
  if (code === "T0001" || code.startsWith("T04")) return "payout";
  if (code.startsWith("T00")) return "capture";
  return "other";
}
